import streamlit as st

# Веб-қосымшаның тақырыбы
st.title("🛡️ Жалған ақпаратты анықтаушы жүйе")
st.write("Бұл қосымша мәтіннің немесе жаңалықтың шынайылығын тексеруге көмектеседі.")

# Қолданушыдан мәтін енгізуді сұрау
user_text = st.text_area("Тексергіңіз келетін мәтінді немесе жаңалықты осында енгізіңіз:")

# Күдікті сөздер тізімі (мысал ретінде)
fake_keywords =["барлығына таратыңыз", "көршілерге жіберіңіз", "ертең өшіреді", "дәрігерлер жасырып отыр","карта нөмірі", "жеңіл ақша", "ұтыс алдыңыз", "балансты толтырыңыз","жүлде ұттыңыз", "карта нөмірін енгізіңіз", "міндетті түрде таратыңыз", "құпия", "барлығына жіберіңіз"]

if st.button("Мәтінді тексеру"):
    if user_text.strip() == "":
        st.warning("Мәтін бос болмауы тиіс!")
    else:
        # Мәтіннен күдікті сөздерді іздеу
        found_keywords = [word for word in fake_keywords if word in user_text.lower()]
        
        if found_keywords:
            st.error(f"⚠️ **Назар аударыңыз! Бұл мәтін фейк болуы мүмкін.**")
            st.write(f"Мәтіннен мынадай күдікті тіркестер табылды: {', '.join(found_keywords)}")
            st.info("Кеңес: Бұл ақпаратты ресми жаңалықтар сайттарынан тексеріңіз.")
        else:
            st.success("✅ **Мәтін қауіпсіз сияқты.**")
            st.write("Күдікті манипуляциялық сөздер анықталмады. Дегенмен, әрқашан ақпаратты тексерген жөн.")
