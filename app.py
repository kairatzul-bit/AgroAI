import streamlit as st

# Беттің баптаулары
st.set_page_config(page_title="Фейк Анықтаушы Жүйе", page_icon="🛡️", layout="centered")

# Дизайн мен тақырып
st.title("🛡️ Жалған ақпаратты интеллектуалды анықтаушы жүйе")
st.write("Бұл қосымша мәтіндегі манипуляциялық белгілерді саралап, фейк болу ықтималдығын пайызымен есептейді.")

# Қолданушыдан мәтін енгізуді сұрау
user_text = st.text_area("Тексергіңіз келетін мәтінді немесе жаңалықты осында енгізіңіз:", height=150)

# Кеңейтілген күдікті сөздер мен тіркестер базасы
fake_keywords = [
    "міндетті түрде таратыңыз", "құпия", "сенбесеңіз көріңіз", 
    "барлығына жіберіңіз", "ғалымдар жасырып отыр", "жүлде ұттыңыз", 
    "тегін ақша", "карта нөмірін жазыңыз", "сенсация", "бәрін өшірмей тұрып оқыңыз",
    "ерекше жаңалық", "шенеуніктер жасырды"
]

if st.button("Мәтінді терең талдаудан өткізу"):
    if user_text.strip() == "":
        st.warning("⚠️ Мәтін бос болмауы тиіс! Өтінемін, мәтін енгізіңіз.")
    else:
        # Мәтінді сөздерге бөлшектеп, ұзындығын есептеу
        words_list = user_text.lower().split()
        total_words = len(words_list)
        
        # Күдікті сөздерді табу
        found_keywords = [word for word in fake_keywords if word in user_text.lower()]
        matches_count = len(found_keywords)
        
        # Қауіптілік пайызын есептеу формуласы
        risk_score = min(matches_count * 25, 100)
        
        # Нәтижелерді көрсету
        st.markdown("---")
        st.subheader("📊 Талдау нәтижелері:")
        
        col1, col2 = st.columns(2)
        with col1:
            st.metric(label="Мәтін ұзындығы", value=f"{total_words} сөз")
        with col2:
            st.metric(label="Анықталған қауіп деңгейі", value=f"{risk_score}%", delta="Жоғары" if risk_score > 50 else "Қауіпсіз", delta_color="inverse")
        
        # Прогресс шкаласы
        st.progress(risk_score / 100)
        
        if risk_score > 50:
            st.error(f"⚠️ **Назар аударыңыз! Бұл мәтіннің фейк (жалған) болу ықтималдығы жоғары.**")
            st.write(f"🔍 **Табылған манипуляциялық тіркестер:** {', '.join(set(found_keywords))}")
            st.info("💡 **Кеңес:** Бұл ақпаратты ресми жаңалықтар агенттіктерінен немесе тексерілген көздерден міндетті түрде тексеріңіз.")
        elif 0 < risk_score <= 50:
            st.warning("⚠️ **Күдікті белгілер байқалды.** Мәтінде сақ болуды талап ететін кейбір сөздер бар.")
            st.write(f"Табылған сөздер: {', '.join(set(found_keywords))}")
        else:
            st.success("✅ **Мәтін қауіпсіз сияқты.**")
            st.write("🎉 Күдікті манипуляциялық сөздер анықталмады. Дегенмен, әрқашан ақпаратты сыни көзқараспен қабылдаған жөн.")
